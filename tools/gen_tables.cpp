// Generates Source/dsp/EqTables.h: the inverse gain law (dB -> pad tap) of
// every band, computed from the nominal network in the analog domain.
#include "dsp/EqNetwork.h"
#include <cstdio>
using namespace vt4;
int main()
{
    struct S { const char* name; int band; int set; bool narrow; };
    const S sets[] = { { "LOW_B", kLow, 1, false }, { "LOW_C", kLow, -1, false }, { "BODY_B", kBody, 1, false }, { "BODY_C", kBody, -1, false },
                       { "PRW_B", kPres, 1, false }, { "PRW_C", kPres, -1, false }, { "PRN_B", kPres, 1, true }, { "PRN_C", kPres, -1, true },
                       { "AIR_B", kAir, 1, false }, { "AIR_C", kAir, -1, false } };
    std::printf ("// Generated by tools/gen_tables.cpp - do not edit.\n// Inverse gain law of each band: pad tap x for |gain| = 0, 0.1, 0.2 ... dB.\n#pragma once\nnamespace vt4 { namespace eqtab {\n");
    std::printf ("constexpr double kStep = 0.1;\n");
    for (const auto& s : sets)
    {
        const double gmax = eq::kMaxGain[s.band] + 0.6;
        const int n = (int) (gmax / 0.1 + 0.5) + 1;
        std::printf ("constexpr int %s_N = %d;\nconstexpr double %s[%d] = {", s.name, n, s.name, n);
        for (int i = 0; i < n; ++i)
        {
            const double g = s.set * 0.1 * i;
            const double x = i == 0 ? eq::nullRatio() : eq::solveTap (s.band, s.set, s.narrow, g);
            std::printf ("%s%.12f", i ? (i % 6 ? ", " : ",\n    ") : "\n    ", x);
        }
        std::printf (" };\n");
    }
    std::printf ("} }\n");
    return 0;
}
